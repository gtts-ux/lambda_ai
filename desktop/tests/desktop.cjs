async function launch(){
  const env={...process.env,LAMBDA_DATA_HOME:data};delete env.ELECTRON_RUN_AS_NODE;
  const packaged=process.env.LAMBDA_PACKAGED_EXECUTABLE;
  app=await electron.launch({executablePath:packaged||require('electron'),args:packaged?[]:[root],cwd:root,env,timeout:30000});
  const page=await app.firstWindow();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',msg=>{if(msg.type()==='error'&&!msg.text().includes('Content Security Policy'))errors.push(msg.text());});
  await page.waitForFunction(()=>document.querySelector('#selected-model')?.textContent!=='Choose a model',null,{timeout:30000});
  return page;
}

